import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Cloudflare E2EE Real-Time Sync
*/
`;

const prod = process.argv[2] === "production";

// Target Obsidian vault plugin directory
const targetVaultDir =
  process.env.OBSIDIAN_VAULT_PLUGIN_DIR ||
  path.resolve("c:/Users/Dark px/Documents/Obsidian Vault/.obsidian/plugins/obsidian-cf-sync");

const copyToVaultPlugin = {
  name: "copy-to-vault",
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length > 0) return;
      try {
        if (!fs.existsSync(targetVaultDir)) {
          fs.mkdirSync(targetVaultDir, { recursive: true });
        }
        if (fs.existsSync("main.js")) {
          fs.copyFileSync("main.js", path.join(targetVaultDir, "main.js"));
        }
        if (fs.existsSync("manifest.json")) {
          fs.copyFileSync("manifest.json", path.join(targetVaultDir, "manifest.json"));
        }
        if (fs.existsSync("styles.css")) {
          fs.copyFileSync("styles.css", path.join(targetVaultDir, "styles.css"));
        }
        console.log(`[esbuild] Successfully deployed plugin bundle to: ${targetVaultDir}`);
      } catch (err) {
        console.warn(`[esbuild] Could not copy plugin to vault dir (${targetVaultDir}):`, err.message);
      }
    });
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [copyToVaultPlugin],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
